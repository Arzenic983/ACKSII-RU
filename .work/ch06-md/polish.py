from common import read,write
from final_edits import EDITS
import re
def strip(s):return re.sub(r' ?\[[^\[\]\n]*[A-Za-z][^\[\]\n]*\]','',s)
units=read('source_units.json');prose=read('prose.json');labels=read('labels.json')
assert not set(prose)&set(labels)
values=prose|labels
values.update(EDITS)
for u in units:
    id=u['id'];s=values[id];en=u['source_markup']
    # Established spell/class-power names; apply only within this chapter.
    for a,b in {'Святилищем':'Убежищем','Святилище':'Убежище','Скрытностью':'Прятанием','Скрытности':'Прятания','Скрытность':'Прятание',
        'Дикая стойкость':'Дикая живучесть','Призыв погоды':'Призвать погоду','Шквал ветра':'Порыв ветра',
        'КОН':'ТЕЛ','КХ':'КЗ','хит-пойнтов':'ОЗ','хит-пойнты':'ОЗ','хит-пойнта':'ОЗ','хит-пойнт':'ОЗ','хит-дайсам':'Костям Здоровья',
        'несмертельного':'нелетального','несмертельный':'нелетальный','несмертельные':'нелетальные',
        'навыками альпинизма':'навыком Альпинизм','следопытства':'Выслеживания','пространства на одном из флангов,это':'пространства на одном из флангов, это',
        'Магическая магия':'Тайная магия','Исправление уродства и инвалидности':'Исцеление увечий и инвалидности'}.items():
        s=s.replace(a,b)
    s=re.sub(r'\bSTR\b','СИЛ',s);s=re.sub(r'\bAC\b','КБ',s);s=re.sub(r'\bхп\b','ОЗ',s,flags=re.I)
    s=re.sub('потайн([а-яё]*)',r'секретн\1',s,flags=re.I)
    if id=='rr.p0271.b026':s=s.replace('срывается с обрыва','срывается с верёвочной переправы')
    if id=='rr.p0271.b027':s=s.replace('сорвется с обрыва','сорвётся с верёвочной переправы')
    if id=='rr.p0279.b007':s=s.replace('становятся весом в золото','становятся на вес золота')
    if id in ('rr.p0296.b014','rr.p0296.b040'):s=s.replace('менять направление движения','менять направление, в которое он обращён,')
    if id=='rr.p0300.b003':s=s.replace('также наносит урон от брызг','также может наносить урон от брызг')
    if id=='rr.p0304.b009':s=s.replace('урон от удара','ударный урон')
    # Recover known source page references left as placeholders by older drafts.
    refs=re.findall(r'\bp\.\s*(\d+(?:[–-]\d+)?)',en)
    for page in refs:
        if '(ссылка)' in s:s=s.replace('(ссылка)',f'(стр. {page})',1)
        elif 'XX XX' in s:s=s.replace('XX XX',page,1)
    s=re.sub(r'(?<![A-Za-z])gp(?![A-Za-z])','зм',s);s=re.sub(r'(?<![A-Za-z])sp(?![A-Za-z])','см',s)
    if u['kind']=='list_item' and en.startswith('♦') and not s.startswith(('♦','- ')):s='♦ '+s
    if id in ('rr.p0271.b010','rr.p0271.b024','rr.p0272.b008','rr.p0272.b012','rr.p0272.b013'):
        s=s.replace('1/3 боевой скорости','трети боевой скорости').replace('1/2 боевой скорости','половины боевой скорости')
    if id=='rr.p0273.b017':s=s.replace('1/4 обычной','четверть обычной')
    if id=='rr.p0275.b006':s=s.replace('16 шестимильных гексов','16 гексов по 6 миль')
    if id=='rr.p0275.b011':s=s.replace('4 шестимильных шестиугольника','4 гекса по 6 миль')
    if id=='rr.p0283.b003':s=s.replace('от 241 человека','241+ человек')
    if id=='rr.p0307.b015':s=s.replace('снимает этот штраф','снимает штраф -4')
    if id=='rr.p0315.b009':s=s.replace('нулевого уровня','0-го уровня').replace('на первый уровень','на 1-й уровень')
    for tag,pattern in [('mundane bludgeoning',r'обычн[а-яё]* дробящ[а-яё]*'),('mundane fire',r'обычн[а-яё]* огненн[а-яё]*'),('mundane piercing',r'обычн[а-яё]* колющ[а-яё]*'),('extraordinary necrotic',r'особ[а-яё]* некротическ[а-яё]*'),('extraordinary luminous',r'особ[а-яё]* урон[а-яё]* излучени[а-яё]*')]:
        if '['+tag+']' in en:
            s=re.sub(r'(?<![А-Яа-яЁё\[])('+pattern+r')(?![А-Яа-яЁё])',r'[\1]',s,flags=re.I)
    values[id]=strip(s)
assert len(values)==len(units)
write('pure_translations.json',values)
